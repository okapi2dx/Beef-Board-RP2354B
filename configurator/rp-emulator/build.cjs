const fs = require('node:fs');
const path = require('node:path');
const source = path.resolve(__dirname, '../beef-config/build');
const output = path.join(__dirname, 'ui');
if (!fs.existsSync(path.join(source, 'index.html'))) throw new Error('Run npm --prefix configurator/desktop run build:ui first.');
fs.mkdirSync(output, { recursive: true });
fs.cpSync(source, output, { recursive: true });
fs.copyFileSync(path.join(__dirname, 'emulator.js'), path.join(output, 'rp-emulator.js'));
const html = fs.readFileSync(path.join(source, 'index.html'), 'utf8');
fs.writeFileSync(path.join(output, 'index.html'), html.replace('<head>', '<head><script src="/rp-emulator.js"></script>'));
console.log('Built standalone RP emulator UI');
